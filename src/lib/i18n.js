/** Translate English text (the key) into the current language, filling {placeholders}. */
export function t(key, vars) {
  let s = lang() === 'el' ? (EL[key] ?? key) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Greek has no plural trick here – choose a key by count for English. */
export const tn = (n, one, many, vars) => t(n === 1 ? one : many, { n, ...vars });

export const kmLabel = () => (lang() === 'el' ? 'χλμ' : 'km');
